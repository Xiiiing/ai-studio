import { test, expect } from '@playwright/test';

const id='012345abcdef';
test.beforeEach(async({request,page})=>{
  await request.post('/__test/reset');
  await page.route('**/*',route=>['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort('blockedbyclient'));
});
test('workflow is navigable and team roles remain separate from approval',async({page,request})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('#workspace h1')).toHaveText('制片总览');
  await expect(page.locator('.metric-card')).toHaveCount(4);
  await page.screenshot({path:'runtime/browser-report/console-dashboard.png',fullPage:true});
  await page.locator('#project-list [data-id="'+id+'"]').click();
  await expect(page.locator('[data-flow-node]')).toHaveCount(10);
  await page.locator('[data-flow-node="screenplay"]').click();
  await expect(page.locator('.node-inspector h3')).toHaveText('剧本与分镜');
  await expect(page.locator('.node-inspector')).toContainText('独立审稿');
  await page.locator('[data-action="flow-fit"]').click();
  await page.screenshot({path:'runtime/browser-report/console-workflow.png',fullPage:true});
  await page.locator('.tabbar [data-tab="team"]').click();
  await expect(page.locator('.department-card')).toHaveCount(4);
  await expect(page.locator('.supervisor-panel')).toContainText('不代表已观看成片');
  await page.setViewportSize({width:390,height:844});
  await expect(page.locator('.department-card').first()).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  await page.screenshot({path:'runtime/browser-report/console-team-mobile.png',fullPage:true});
  await request.post('/__test/failure',{data:{route:'/flow'}});
  await page.locator('.topbar [data-action="refresh"]').click();
  await expect(page.locator('#workspace')).toContainText('历史回执读取失败');
  const calls=await(await request.get('/__test/calls')).json();
  expect(calls.filter(c=>c.method==='POST'&&c.path.startsWith('/api/'))).toEqual([]);
  expect(errors).toEqual([]);
});
test('saved optional producer binding enables delegated creation but not final approval',async({page,request})=>{
  await page.goto('/');
  await page.locator('[data-action="new-project"]').first().click();
  await expect(page.locator('#project-dialog option[value="delegated"]')).toBeDisabled();
  await page.locator('#project-dialog [data-action="close-dialog"]').first().click();
  await page.locator('.main-nav [data-action="models"]').click();
  await page.locator('#role-executive_producer').selectOption('writer');
  await page.locator('[data-model-action="save"]').click();
  await expect(page.locator('[data-model-action="save"]')).toBeDisabled();
  await page.locator('[data-action="new-project"]').first().click();
  await expect(page.locator('#project-dialog option[value="delegated"]')).toBeEnabled();
  await page.locator('#project-dialog [name="team_mode"]').selectOption('delegated');
  await page.locator('#project-dialog [name="brief"]').fill('成年修表师与邻居合作解开旧时钟的谜题，结局温暖。');
  await page.screenshot({path:'runtime/browser-report/console-create.png',fullPage:true});
  await page.locator('#project-dialog button[type="submit"]').click();
  await expect(page.locator('#project-dialog')).not.toBeVisible();
  await expect(page.locator('.project-attention-banner')).toContainText('审看并确认终片');
  await page.locator('.tabbar [data-tab="decisions"]').click();
  await expect(page.locator('form[data-form="final"]')).toBeVisible();
  const calls=await(await request.get('/__test/calls')).json();
  expect(calls.find(c=>c.path==='/api/factory/projects'&&c.method==='POST')?.body.team_mode).toBe('delegated');
  expect(calls.filter(c=>c.method==='POST'&&/decision|cloud|generate|\/test$/.test(c.path))).toEqual([]);
});
